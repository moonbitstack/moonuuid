"""Write src/<language>_test.mbt from another implementation of RFC 9562.

The other implementation runs through integration/<language>-interop, which
prints the identifiers it makes and the fields it reads (the line format is in
src/examples/03-interop/main.mbt). This script turns both into tests here, so
`moon test` replays what that implementation decided without needing it
installed.

Usage: python3 scripts/gen_vectors.py go|rust [--go-proxy URL]
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_interop import REFUSALS, ROOT, SPELLINGS, ask  # noqa: E402

# The identifiers both sides can pin down: the same label, made from the same
# input, has to be the same identifier. A language that cannot make one of
# these simply leaves it out.
SHARED = {
    "v1-rfc": (
        "let ticks = 0x1EC9414C232AB00L",
        "@moonuuid.v1(ticks~, clock_seq=0x33C8, node=0x9F6BDECED846L)",
    ),
    "v6-rfc": (
        "let ticks = 0x1EC9414C232AB00L",
        "@moonuuid.v6(ticks~, clock_seq=0x33C8, node=0x9F6BDECED846L)",
    ),
    "v3-dns-www": ("", '@moonuuid.v3(@moonuuid.namespace_dns, "www.example.com")'),
    "v5-dns-www": ("", '@moonuuid.v5(@moonuuid.namespace_dns, "www.example.com")'),
    "v5-url-example": (
        "",
        '@moonuuid.v5(@moonuuid.namespace_url, "https://example.org/")',
    ),
    "v4-zero": ("", "@moonuuid.v4(Bytes::make(16, 0))"),
    "v4-count": ("", "@moonuuid.v4(Bytes::makei(16, i => i.to_byte()))"),
    "v8-count": ("", "@moonuuid.v8(Bytes::makei(16, i => i.to_byte()))"),
}

VARIANTS = {"Ncs", "Rfc", "Microsoft", "Future"}


def quote(text: str) -> str:
    return '"%s"' % text.replace("\\", "\\\\").replace('"', '\\"')


def field_asserts(text: str, row: list[str]) -> str:
    """The assertions for one identifier, as the other implementation read it."""
    _, canonical, version, variant, stamp, seq, node, digits, urn = row
    lines = [
        "  let u = @moonuuid.parse(%s)" % quote(text),
        "  assert_eq(u.to_string(), %s)" % quote(canonical),
        "  assert_eq(u.hex(), %s)" % quote(digits),
        "  assert_eq(u.urn(), %s)" % quote(urn),
        "  assert_eq(u.version(), %s)"
        % ("None" if version == "-" else "Some(%s)" % version),
        "  assert_eq(u.variant(), @moonuuid.%s)" % variant,
    ]
    if stamp != "-":
        lines.append("  assert_eq(u.time(), %sL)" % stamp)
    if seq != "-":
        lines.append("  assert_eq(u.clock_seq(), %s)" % seq)
    if node != "-":
        lines.append("  assert_eq(u.node(), %sL)" % node)
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("language", choices=["go", "rust"])
    parser.add_argument("--go-proxy", default="")
    args = parser.parse_args()
    if args.go_proxy:
        os.environ["GOPROXY"] = args.go_proxy

    made = dict(line.split("\t") for line in ask(args.language, ["make"]))
    keep = [SPELLINGS[0], SPELLINGS[2], SPELLINGS[3], SPELLINGS[4], SPELLINGS[5], SPELLINGS[6]]
    to_read = sorted(set(made.values()) | set(keep) | set(REFUSALS))
    rows = {}
    for line in ask(args.language, ["read", *to_read]):
        parts = line.split("\t")
        rows[parts[0]] = parts

    blocks = []
    generation = [label for label in SHARED if label in made]
    body = []
    for label in generation:
        setup, call = SHARED[label]
        if setup:
            body.append("  " + setup)
        body.append(
            "  assert_eq(\n    %s.to_string(),\n    %s,\n  )"
            % (call, quote(made[label]))
        )
    blocks.append('///|\ntest "%s: the same input gives the same identifier" {\n%s\n}' % (args.language, "\n".join(body)))

    for text in to_read:
        row = rows.get(text)
        if row is None or len(row) < 9 or row[1] == "!":
            continue
        name = "reads an identifier it was given" if text in keep else "reads one of its own"
        blocks.append(
            '///|\ntest "%s: %s, %s" {\n%s\n}'
            % (args.language, name, text, field_asserts(text, row))
        )

    refused = []
    for text in REFUSALS:
        row = rows.get(text)
        if row and row[1] == "!":
            refused.append(
                "  assert_false(try {\n    ignore(@moonuuid.parse(%s))\n    true\n  } catch {\n    _ => false\n  })"
                % quote(text)
            )
    blocks.append('///|\ntest "%s: what it refuses is refused here" {\n%s\n}' % (args.language, "\n".join(refused)))

    out = ROOT / "src" / ("%s_test.mbt" % args.language)
    header = (
        "// Generated by scripts/gen_vectors.py from the %s implementation. Do not edit.\n"
        % {"go": "github.com/google/uuid", "rust": "uuid crate"}[args.language]
    )
    out.write_text(header + "\n" + "\n\n".join(blocks) + "\n", encoding="utf-8", newline="\n")
    print("%s <- %d tests" % (out.relative_to(ROOT), len(blocks)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
